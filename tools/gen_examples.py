# Packs the example texts and recipes of app/core/pw_examples.inc and the module descriptions of pw_help.inc (the readable sources) into app/core/pw_examples_z.inc:
# the strings with their common pieces replaced by one byte (0x80 and up) that names an entry of a dictionary
# (entries may use other entries). pw_presets.c expands them when an example is shown or built. About half the flash.
#   tools/gen_examples.py          write the packed file
#   tools/gen_examples.py --fast   write it without the dictionary (seconds, not a minute: only for tools/check_text.sh; run it plain before a build you keep)
#   tools/gen_examples.py --check  fail if it is not what the source gives (tests/run_tests.sh does this)
import re, sys, os, collections
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src = open(os.path.join(root, "app/core/pw_examples.inc")).read()
lit = r'"(?:[^"\\]|\\.)*"'
ents = re.findall(r'\{(PW_T_\w+),\s*((?:' + lit + r'\s*)+),\s*((?:' + lit + r'\s*)+)\}', src)
def unq(g):
    out = ""
    for m in re.finditer(lit, g):
        out += re.sub(r'\\(.)', lambda k: {"n": "\n"}.get(k.group(1), k.group(1)), m.group(0)[1:-1])
    return out
rows = [(t, unq(a), unq(b)) for t, a, b in ents]
assert len(rows) == src.count("{PW_T_") - src.count("{PW_T_", 0, src.index("pw_examples[]")), "unparsed example entry"
hsrc = open(os.path.join(root, "app/core/pw_help.inc")).read()
hrows = [(t, unq(h)) for t, h in re.findall(r'\{(PW_T_\w+),\s*((?:' + lit + r'\s*)+)\}', hsrc)]
assert len(hrows) == hsrc.count("{PW_T_"), "unparsed help entry"
strs = [x for r in rows for x in r[1:]] + [h for _, h in hrows]
assert all(ord(c) < 128 for x in strs for c in x)
import hashlib, json
# (the dictionary search takes over a minute: its result is kept in tests/out, keyed on the strings, and used again while they are the same)
cache = os.path.join(root, "tests/out/ex_dict_" + hashlib.sha1("\0".join(strs).encode()).hexdigest()[:16] + ".json")
dic = []
cur = list(strs)
if "--fast" not in sys.argv and os.path.exists(cache):
    saved = json.load(open(cache)); dic, cur = saved["dic"], saved["cur"]
while len(dic) < 128 and "--fast" not in sys.argv and not os.path.exists(cache):   # (--fast: no dictionary, for the quick text-fit check only)
    cnt = collections.Counter()
    for x in cur + dic:
        for L in range(3, 28):
            for i in range(len(x) - L + 1):
                t = x[i:i + L]
                if all(ord(c) < 128 for c in t): cnt[t] += 1
    best, bg = None, 0
    for t, c in cnt.items():
        g = (len(t) - 1) * c - (len(t) + 1) - 4
        if g > bg: best, bg = t, g
    if not best or bg < 6: break
    ch = chr(128 + len(dic))
    cur = [x.replace(best, ch) for x in cur]
    dic = [d.replace(best, ch) for d in dic]
    dic.append(best)
if "--fast" not in sys.argv and not os.path.exists(cache):
    os.makedirs(os.path.dirname(cache), exist_ok=True)
    for old_c in os.listdir(os.path.dirname(cache)):
        if old_c.startswith("ex_dict_"): os.remove(os.path.join(os.path.dirname(cache), old_c))
    json.dump({"dic": dic, "cur": cur}, open(cache, "w"))
def esc(x):
    o = ""
    for c in x:
        if ord(c) >= 128: o += "\\%03o" % ord(c)
        elif c in '"\\': o += "\\" + c
        elif c == "\n": o += "\\n"
        else: o += c
    return o
def chunks(x):   # (keeps lines short; adjacent literals join)
    return '"\n     "'.join(re.findall(r'(?:\\[0-7]{3}|\\.|[^\\]){1,100}', esc(x)))
out = "/* SPDX-License-Identifier: GPL-3.0-only\n * GENERATED by tools/gen_examples.py from pw_examples.inc: do not edit. Strings with pieces replaced by dictionary bytes (0x80+). */\n"
out += "static const char *const ex_dict[] = {\n" + "".join('    "%s",\n' % esc(d) for d in dic) + "};\n"
out += "static const struct { uint8_t type; const char *text, *recipe; } pw_examples[] = {\n"
for (t, _, _), (a, b) in zip(rows, zip(cur[0:2 * len(rows):2], cur[1:2 * len(rows):2])):
    out += '    {%s, "%s",\n     "%s"},\n' % (t, chunks(a), chunks(b))
out += "};\nstatic const struct { uint8_t type; const char *text; } pw_helps[] = {\n"
for (t, _), h in zip(hrows, cur[2 * len(rows):]):
    out += '    {%s, "%s"},\n' % (t, chunks(h))
out += "};\n"
dst = os.path.join(root, "app/core/pw_examples_z.inc")
if "--check" in sys.argv:
    if not os.path.exists(dst) or open(dst).read() != out:
        print("app/core/pw_examples_z.inc is out of date: run tools/gen_examples.py"); sys.exit(1)
else:
    open(dst, "w").write(out)
    print(len(rows), "examples,", len(dic), "dictionary entries; strings", sum(len(x) + 1 for x in strs), "->", sum(len(x) + 1 for x in cur) + sum(len(d) + 1 for d in dic) + 4 * len(dic))
