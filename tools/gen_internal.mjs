// web/factory_bank.json -> app/core/pw_internal.inc: the INTERNAL sample bank, built into the firmware (and the
// emulator): the 16 factory sounds as SEA streams (web/sea.js), each at its own rate, padded to whole words.
//   node tools/gen_internal.mjs          write the file
//   node tools/gen_internal.mjs --check  fail if it is out of date (tests/run_tests.sh)
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..');
const SEA = createRequire(import.meta.url)(path.join(root, 'web', 'sea.js'));
const bank = JSON.parse(fs.readFileSync(path.join(root, 'web', 'factory_bank.json'), 'utf8'))
  ;
// The firmware's code and constants share one 565 KB region (XIP), so INTERNAL is kept small (about 16 KB): each
// sound is trimmed, capped in length (a 25 ms fade at the cap) and the low ones are halved in rate.
// [name, longest in ms, rate divisor]. The web page's "Factory to A/B" copies the full-length sounds.
const LIMIT = { BD: [450, 2], 'TOM L': [300, 2], 'TOM M': [300, 2], 'TOM H': [300, 2], COWBELL: [250, 2], 'HAT OPEN': [220, 1], CRASH: [300, 1],
  VIBES: [350, 1], SOFT: [350, 1], FUTURE: [250, 1], CLAP: [120, 1] };
// Which sounds are built in: none for now (the code region is full); name them here to bring them back, e.g. ['BD', 'SNARE'].
const BUILT_IN = [];
let streams = [], rows = [], off = 0;
for (const f of bank.filter((s) => BUILT_IN.includes(s.name))) {
  const u = Buffer.from(f.d, 'base64'), pcm = new Int16Array(u.buffer, u.byteOffset, u.length >> 1);
  const [ms, div] = LIMIT[f.name] || [1000, 1];
  let y = SEA.cut(pcm, f.rate).data, rate = f.rate;
  if (div > 1) {   // a box filter, then every div-th frame
    const z = new Int16Array(Math.floor(y.length / div));
    for (let i = 0; i < z.length; i++) { let s = 0; for (let k = 0; k < div; k++) s += y[i * div + k]; z[i] = Math.round(s / div); }
    y = z; rate = Math.round(rate / div);
  }
  const cap = Math.round(rate * ms / 1000);
  if (y.length > cap) {
    y = y.slice(0, cap); const fd = Math.min(cap, Math.round(rate * 0.025));
    for (let i = 0; i < fd; i++) y[cap - fd + i] = Math.round(y[cap - fd + i] * (1 - i / Math.max(1, fd - 1)));
  }
  if (y.length % 20) { const w = new Int16Array(Math.ceil(y.length / 20) * 20); w.set(y); y = w; }
  const e = SEA.encode(y, SEA.FPC);
  rows.push(`    {"${f.name}", ${rate}u, ${e.frames}u, ${off}u},`);
  streams.push(e.data); off += e.data.length;
}
const all = Buffer.concat(streams.map((s) => Buffer.from(s)));
let text = `/* generated by tools/gen_internal.mjs from web/factory_bank.json: the INTERNAL sample bank (SEA streams, ${all.length} bytes) */\n`;
const n = rows.length;
text += `#define PW_INTERNAL_N ${n}\n`;
text += `static const struct { const char *name; uint32_t rate, frames, off; } pw_internal[${n || 1}] = {\n${n ? rows.join('\n') : '    {"", 0u, 0u, 0u},'}\n};\n`;
text += `static const uint8_t pw_internal_sea[${all.length || 4}] = {\n`;
if (!all.length) text += '    0,0,0,0,\n';
for (let i = 0; i < all.length; i += 24) text += '    ' + Array.from(all.subarray(i, i + 24)).join(',') + ',\n';
text += '};\n';
const out = path.join(root, 'app', 'core', 'pw_internal.inc');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) { console.error('app/core/pw_internal.inc is out of date: run tools/gen_internal.mjs'); process.exit(1); }
} else { fs.writeFileSync(out, text); console.log(`INTERNAL bank: ${n} sounds, ${all.length} bytes`); }
