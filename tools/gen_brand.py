"""brand/brand.json -> the places that need PATCHWERK's brand colors as code:
   app/core/pw_brand.h, base/bsp/loader/pw_brand.h, base/device/pw_brand.h  (C: the default palette, the loader's screen, the update screen)
   web/brand.json (read by web/build_page.py: the page's colors, the mark and the tab icon)
   python3 tools/gen_brand.py          write them
   python3 tools/gen_brand.py --check  fail if they are not what brand.json gives"""
import json, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
b = json.load(open(root / 'brand/brand.json'))
def rgb(h):
    h = h.lstrip('#'); return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
def trip(h): return '%d, %d, %d' % rgb(h)
col = lambda k: b['accent'] if k == 'accent' else b['cats'][k]
lines = ['/* SPDX-License-Identifier: GPL-3.0-only */', '/* GENERATED by tools/gen_brand.py from brand/brand.json: do not edit (change the json, run  sh tools/gen_brand.sh). */',
         '#ifndef PW_BRAND_H', '#define PW_BRAND_H', '#define BR_NAME "%s"' % b['name']]
for k in ('accent', 'ok', 'warn', 'bad'): lines.append('#define BR_%s %s' % (k.upper(), trip(b[k])))
for k, v in b['cats'].items(): lines.append('#define BR_%s %s' % (k.upper(), trip(v)))
for i, k in enumerate(b['cables']): lines.append('#define BR_CABLE%d %s' % (i, trip(col(k))))
lines.append('#endif')
hdr = '\n'.join(lines) + '\n'
files = {root / 'app/core/pw_brand.h': hdr, root / 'base/bsp/loader/pw_brand.h': hdr, root / 'base/device/pw_brand.h': hdr,
         root / 'web/brand.json': json.dumps({k: v for k, v in b.items() if k != '_'}, indent=1) + '\n'}
bad = 0
for p, t in files.items():
    if '--check' in sys.argv:
        if not p.exists() or p.read_text() != t: print('out of date:', p.relative_to(root)); bad = 1
    else: p.write_text(t)
if '--check' in sys.argv: sys.exit(bad)
print('brand: %s, accent %s' % (b['name'], b['accent']))
