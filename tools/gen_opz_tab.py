#!/usr/bin/env python3
"""Writes app/core/pw_opz_tab.inc: the OPM/OPZ lookup tables of ymfm (BSD-3-Clause, Aaron Giles), taken from ymfm_fm.ipp.
usage: gen_opz_tab.py path/to/ymfm_fm.ipp > app/core/pw_opz_tab.inc"""
import re, sys
src = open(sys.argv[1]).read()
def block(name):
    m = re.search(name + r'\[[^\]]*\](?:\[[^\]]*\])?\s*=\s*\{(.*?)\n\t\};', src, re.S)
    return m.group(1)
sin = [int(x, 16) for x in re.findall(r'0x([0-9a-f]{3})', block('s_sin_table'))]
pw = [int(x, 16) for x in re.findall(r'X\(0x([0-9a-f]{3})\)', block('s_power_table'))]
ph = [int(x) for x in re.findall(r'\d+', block('s_phase_step'))]
dt = [int(x) for x in re.findall(r'\d+', block('s_detune_adjustment'))]
inc = [int(x, 16) for x in re.findall(r'0x([0-9a-f]{8})', block('s_increment_table'))]
assert len(sin) == 256 and len(pw) == 256 and len(ph) == 768 and len(dt) == 128 and len(inc) == 64, (len(sin), len(pw), len(ph), len(dt), len(inc))
def arr(name, t, vals, per, fmt):
    print('static const %s %s[%d] PW_DSP_DATA = {' % (t, name, len(vals)))
    for i in range(0, len(vals), per):
        print('    ' + ','.join(fmt % v for v in vals[i:i + per]) + ',')
    print('};')
print('/* The OPM/OPZ tables (the YM2151 and YM2414 chips), generated by tools/gen_opz_tab.py from ymfm (https://github.com/aaronsgiles/ymfm).')
print(' * ymfm: BSD-3-Clause, Copyright (c) 2021, Aaron Giles. See LICENSING.md. */')
arr('dx_sin', 'uint16_t', sin, 16, '0x%03x')
arr('dx_pow', 'uint16_t', pw, 16, '0x%03x')
arr('dx_step', 'uint32_t', ph, 12, '%d')
arr('dx_det', 'uint8_t', dt, 16, '%d')
arr('dx_inc', 'uint32_t', inc, 8, '0x%08x')
