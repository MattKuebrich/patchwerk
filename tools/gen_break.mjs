// web/break_src.json -> app/core/pw_break.inc: the drum break a new SAMPLER starts with (its RAM sound), as one SEA stream
// (22.05 kHz, mono, one second; the firmware decodes it into the SAMPLER's RAM and doubles the rate).
//   node tools/gen_break.mjs          write the file
//   node tools/gen_break.mjs --check  fail if it is out of date (tests/run_tests.sh)
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..');
const SEA = createRequire(import.meta.url)(path.join(root, 'web', 'sea.js'));
const f = JSON.parse(fs.readFileSync(path.join(root, 'web', 'break_src.json'), 'utf8'))[0];
const u = Buffer.from(f.d, 'base64');
let y = new Int16Array(u.buffer, u.byteOffset, u.length >> 1);
if (y.length % 20) { const w = new Int16Array(Math.ceil(y.length / 20) * 20); w.set(y); y = w; }
const e = SEA.encode(y, SEA.FPC);
const all = Buffer.from(e.data);
let text = `/* generated by tools/gen_break.mjs from web/break_src.json: the SAMPLER's starting sound (a SEA stream, ${all.length} bytes) */\n`;
text += `#define PW_BREAK_FRAMES ${f.d ? Math.floor(u.length / 2) : 0}u\n#define PW_BREAK_RATE ${f.rate}u\n#define PW_BREAK_CODED ${e.frames}u\n`;
text += `static const uint8_t pw_break_sea[${all.length}] = {\n`;
for (let i = 0; i < all.length; i += 24) text += '    ' + Array.from(all.subarray(i, i + 24)).join(',') + ',\n';
text += '};\n';
const out = path.join(root, 'app', 'core', 'pw_break.inc');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) { console.error('app/core/pw_break.inc is out of date: run tools/gen_break.mjs'); process.exit(1); }
} else { fs.writeFileSync(out, text); console.log(`SAMPLER break: ${all.length} bytes`); }
