"""Draw PATCHWERK's screen fonts into app/core/pw_fonts.h (run by hand when the fonts change; the header is
committed, so neither build needs Pillow for it).

Barlow Semi Condensed (SIL OFL 1.1, base/assets/fonts) at three sizes (and the splash's nine letters at a fourth), anti-aliased:
  XS the patch diagram's boxes   SemiBold 12 px, ASCII 32..126
  S  labels, body text, lists    SemiBold 14 px, ASCII 32..126
  M  titles, knob values         Bold 19 px, ASCII 32..126
  L  the splash's wordmark       Bold 34 px, only A C E H K P R T W (PATCHWERK): a whole L font was 11 KB, this is under 3

Glyph format: per glyph its advance, the ink box (x from the pen, y from the top of the capitals, w, h) and the
offset of its bitmap: rows of w pixels, 4-bit alpha, two pixels a byte (high nibble first), each row whole bytes.
A text's y is the top of its capitals; FONT.cap is their height, FONT.lh the line advance."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "base" / "assets" / "fonts"
SIZES = [("XS", "BarlowSemiCondensed-SemiBold.ttf", 12, 126, 0),
         ("S", "BarlowSemiCondensed-SemiBold.ttf", 14, 126, 0),
         ("M", "BarlowSemiCondensed-Bold.ttf", 19, 126, 0),
         ("L", "BarlowSemiCondensed-Bold.ttf", 34, 87, 1, 65, "ACEHKPRTW")]   # the splash's wordmark only: just the nine letters of PATCHWERK


def render(name, ttf, px, last, tracking, first=32, only=None):
    font = ImageFont.truetype(str(FONTS / ttf), px)
    ascent, descent = font.getmetrics()
    cap_top = font.getbbox("H", anchor="ls")[1]          # negative: above the baseline
    cap = -cap_top
    glyphs, bits = [], bytearray()
    for code in range(first, last + 1):
        ch = chr(code)
        adv = int(round(font.getlength(ch))) + tracking
        img = Image.new("L", (adv + 2 * px, 3 * px), 0)
        d = ImageDraw.Draw(img)
        ox, base = px, 2 * px
        d.text((ox, base), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox() if only is None or ch in only else None
        if not box:
            glyphs.append((len(bits), 0, 0, 0, 0, adv))
            continue
        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        off = len(bits)
        for y in range(y0, y1):
            row = [img.getpixel((x, y)) for x in range(x0, x1)]
            q = [min(15, (v * 15 + 127) // 255) for v in row]
            if len(q) & 1:
                q.append(0)
            for i in range(0, len(q), 2):
                bits.append(q[i] << 4 | q[i + 1])
        glyphs.append((off, w, h, x0 - ox, y0 - (base - cap), adv))
    lh = cap + descent + max(3, px // 5)
    return name, glyphs, bits, cap, lh, last, first


def main():
    out = ["/* SPDX-License-Identifier: GPL-3.0-only", " * Generated by tools/gen_fonts.py: Barlow Semi Condensed (SIL OFL 1.1,",
           " * base/assets/fonts/Barlow-OFL.txt). Do not edit. */",
           "#ifndef PW_FONTS_H", "#define PW_FONTS_H", "#include <stdint.h>",
           "typedef struct { uint16_t off; uint8_t w, h; int8_t x, y; uint8_t adv; } pw_glyph;",
           "typedef struct { const pw_glyph *g; const uint8_t *bits; uint8_t first, last, cap, lh; } pw_fontdef;"]
    total = 0
    for spec in SIZES:
        name, glyphs, bits, cap, lh, last, first = render(*spec)
        total += len(bits) + 7 * len(glyphs)
        out.append(f"static const pw_glyph pw_font_{name}_g[{len(glyphs)}] = {{")
        for i in range(0, len(glyphs), 6):
            out.append("    " + " ".join("{%d,%d,%d,%d,%d,%d}," % g for g in glyphs[i:i + 6]))
        out.append("};")
        out.append(f"static const uint8_t pw_font_{name}_bits[{len(bits)}] = {{")
        for i in range(0, len(bits), 24):
            out.append("    " + ",".join(str(b) for b in bits[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const pw_fontdef pw_font_{name} = {{pw_font_{name}_g, pw_font_{name}_bits, {first}, {last}, {cap}, {lh}}};")
    out.append("#endif")
    (ROOT / "app" / "core" / "pw_fonts.h").write_text("\n".join(out) + "\n")
    print(f"pw_fonts.h: {total} bytes of font data")


if __name__ == "__main__":
    main()
