"""assets/dx/INTERNAL.syx -> app/core/pw_dxbank.inc (FM-DX's built-in bank: 128 bytes a voice).
   python3 tools/gen_dx_inc.py          write the file
   python3 tools/gen_dx_inc.py --check  fail if it is out of date (run_tests.sh)"""
import os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
d = open(os.path.join(root, "assets", "dx", "INTERNAL.syx"), "rb").read()
assert d[:4] == bytes([0xF0, 0x43, 0x00, 0x04]) and len(d) == 4104 and d[-1] == 0xF7, "not a TX81Z 32-voice bank"
n = d[6:6 + 4096]
vs = [n[i * 128:(i + 1) * 128] for i in range(32)]
s = "static const uint8_t dx_internal[%d * 128] = {\n" % len(vs)
for v in vs:
    s += "    " + ",".join(str(x) for x in v) + ",   /* " + v[57:67].decode().strip() + " */\n"
text = "/* generated by tools/gen_dx_inc.py from assets/dx/INTERNAL.syx: FM-DX's built-in bank */\n#define DX_INTERNAL_N %d\n%s};\n" % (len(vs), s)
path = os.path.join(root, "app", "core", "pw_dxbank.inc")
if "--check" in sys.argv:
    if not os.path.exists(path) or open(path).read() != text:
        sys.exit("app/core/pw_dxbank.inc is out of date: run tools/gen_dx_inc.py")
else:
    open(path, "w").write(text)
