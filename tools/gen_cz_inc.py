"""assets/cz/INTERNAL.syx -> app/core/pw_czbank.inc (the CZ module's built-in bank: 144 bytes a tone).
   python3 tools/gen_cz_inc.py          write the file
   python3 tools/gen_cz_inc.py --check  fail if it is out of date (run_tests.sh)"""
import os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
def tones(fn):
    d = open(os.path.join(root, "assets", "cz", fn), "rb").read()
    out, i = [], 0
    while i < len(d):
        j = d.index(0xF7, i)
        n = d[i + 7:j]
        assert len(n) == 288, (fn, len(n))
        out.append(bytes((n[2 * k] & 15) | ((n[2 * k + 1] & 15) << 4) for k in range(144)))
        i = j + 1
    return out
def arr(name, ts):
    s = "static const uint8_t %s[%d * 144] = {\n" % (name, len(ts))
    for t in ts:
        s += "    " + ",".join(str(x) for x in t) + ",   /* " + t[128:].decode().strip() + " */\n"
    return s + "};\n"
a = tones("INTERNAL.syx")
text = "/* generated by tools/gen_cz_inc.py from the .syx files in assets/cz: the CZ's built-in bank */\n#define CZ_INTERNAL_N %d\n%s" % (len(a), arr("cz_internal", a))
path = os.path.join(root, "app", "core", "pw_czbank.inc")
if "--check" in sys.argv:
    if not os.path.exists(path) or open(path).read() != text:
        sys.exit("app/core/pw_czbank.inc is out of date: run tools/gen_cz_inc.py")
else:
    open(path, "w").write(text)
