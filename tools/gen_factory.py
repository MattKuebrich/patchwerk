"""Packs the factory patches saved by gen_factory (DIR/NN.bin, DIR/plays.txt) into app/core/pw_factory_data.inc: patch 0 as it is
(it is the dictionary), the rest with tools/lz.py against it. usage: gen_factory.py DIR OUT.inc"""
import glob, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lz
d = sys.argv[1]
blobs = [open(f, 'rb').read() for f in sorted(glob.glob(d + '/[0-9][0-9].bin'))]
plays = [int(x) for x in open(d + '/plays.txt').read().split()]
dic = blobs[0]
data = bytearray(dic)
off = [0, len(dic)]
for b in blobs[1:]:
    c = lz.compress(b, dic)
    assert lz.decompress(c, dic) == b
    data += c
    off.append(len(data))
mx = max(len(b) for b in blobs)
mask = sum(1 << i for i in plays)
o = ['/* SPDX-License-Identifier: GPL-3.0-only',
     ' * The factory patches, packed. GENERATED by tools/gen_factory.sh from tools/factory_src.inc: do not edit by hand. */',
     '#define FAC_DICT %du' % len(dic),
     '#define FAC_MAX %du   /* the largest patch, unpacked */' % ((mx + 63) // 64 * 64),
     '#define FAC_PLAYS 0x%xull   /* the patches that play at once */' % mask,
     'static const uint16_t fac_off[%d] = {' % len(off)]
for i in range(0, len(off), 12):
    o.append('    ' + ', '.join(str(x) for x in off[i:i + 12]) + ',')
o.append('};')
o.append('static const uint8_t fac_data[%d] = {' % len(data))
for i in range(0, len(data), 24):
    o.append('    ' + ','.join(str(x) for x in data[i:i + 24]) + ',')
o.append('};')
open(sys.argv[2], 'w').write('\n'.join(o) + '\n')
print('factory patches: %d, %d bytes packed (%d unpacked)' % (len(blobs), len(data), sum(len(b) for b in blobs)))
